export function resolveTaiwanDistrictCoords(address: string): DistrictCoord | undefined {
  if (!address) return undefined;

  // 統一全半形與台/臺
  const normalized = address.replace(/臺/g, '台').trim();

  // 1. 優先透過郵遞區號 3 碼匹配 (支援 3 碼或 5 碼如 115 / 11578)
  const zipMatch = normalized.match(/\b(\d{3})(?:\d{2,3})?\b/);
  if (zipMatch) {
    const zip3 = zipMatch[1];
    const targetDistrict = ZIPCODE_TO_DISTRICT[zip3];
    if (targetDistrict && TW_DISTRICT_MAP[targetDistrict]) {
      return { ...TW_DISTRICT_MAP[targetDistrict] };
    }
  }

  // 2. 透過完整或部分行政區比對 (支援「台北市南港區」或「台北市南港路」)
  for (const [key, coord] of Object.entries(TW_DISTRICT_MAP)) {
    const county = key.slice(0, 3);
    const districtFullName = key.slice(3);
    const districtBaseName = districtFullName.replace(/[區鄉鎮市]$/, '');

    if (
      normalized.includes(key) ||
      (normalized.includes(county) &&
        (normalized.includes(districtFullName) || normalized.includes(districtBaseName)))
    ) {
      return { ...coord };
    }
  }

  // 3. Fallback: 比對縣市中心點
  for (const [county, coord] of Object.entries(COUNTY_CENTER_MAP)) {
    if (normalized.includes(county)) {
      return { ...coord };
    }
  }

  return undefined;
}
